// Offline production UI regression. All API and non-local network requests are intercepted.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
const { chromium } = await import(pathToFileURL(path.join(os.homedir(), '.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs')).href);
const fixtures = JSON.parse(fs.readFileSync('tmp/evidence-fixtures.json','utf8'));
const xr = JSON.parse(fs.readFileSync('tmp/sprint-6b/browser-fixtures.json','utf8'));
const browser = await chromium.launch({channel:'msedge',headless:true});
const checks = [], actions = [], errors = [];
const dir = 'docs/review/sprint-11b/evidence-integrity'; fs.mkdirSync(dir,{recursive:true});
try {
 for (const [width,height] of [[1920,1080],[1440,900],[390,844]]) {
  const context = await browser.newContext({viewport:{width,height},reducedMotion:'reduce'});
  await context.addInitScript(() => { window.EventSource = class { constructor() {window.__offlineStream=this;} close() {} }; });
  await context.route('**/*', async route => {
   const url = new URL(route.request().url());
   if (!['127.0.0.1','localhost'].includes(url.hostname)) return route.abort();
   if (!url.pathname.startsWith('/api/')) return route.continue();
   if (url.pathname === '/api/health') return route.continue();
   if (url.pathname === '/api/experiments') {
    const body = route.request().postDataJSON(); actions.push({width,...body});
    assert.ok(['design','run','interpret'].includes(body.action));
    return route.fulfill({json:fixtures[body.action]});
   }
   throw Error(`Unexpected API call: ${url.pathname}`);
  });
  const page = await context.newPage(); page.on('pageerror',e=>errors.push(e.message));
  const nav = name => page.getByRole('navigation',{name:'Experiment workspaces'}).getByRole('button',{name,exact:true}).click();
  const sourceButton = () => page.locator('.source-connection button');
  const emit = async data => { await page.evaluate(data=>window.__offlineStream.onmessage(new MessageEvent('message',{data:JSON.stringify(data)})),data); await page.waitForFunction(state => [...document.querySelectorAll('.source-option')].at(-1)?.textContent.includes(state), data.state); };
  const overflow = async state => { assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,`${width}: ${state} overflow`); checks.push({width,state}); };
  await page.goto('http://127.0.0.1:3143',{waitUntil:'domcontentloaded'});
  await nav('Experiment');
  await page.getByRole('button',{name:/Ask Your Own Question/}).click();
  await page.getByRole('textbox',{name:'Your research question'}).fill(fixtures.design.design.researchQuestion);
  await page.getByRole('button',{name:'USE THIS QUESTION',exact:true}).click();
  await page.getByRole('button',{name:'Design with Meta',exact:false}).click();
  await page.getByRole('button',{name:'Approve & Run Experiment',exact:true}).click();
  await page.getByRole('group',{name:'Select recorded condition'}).waitFor();
  await page.getByRole('button',{name:'Explain with Meta',exact:false}).first().click();
  await page.locator('.scientist-next').waitFor();
  await page.getByRole('button',{name:'Ask CausalFly',exact:true}).click();
  const assistant = page.getByRole('dialog');
  await assistant.getByLabel('Ask about this experiment').fill('What changed under intervention?');
  await assistant.getByRole('button',{name:'Submit question locally'}).click();
  await assistant.getByText(/Measured control versus silence/).waitFor();
  await page.getByRole('button',{name:'Close CausalFly Assistant'}).click();
  await page.getByRole('button',{name:/Ask another question/}).click();
  const newQuestion = 'Does silencing alternate_c change output in a new investigation?';
  await page.getByRole('textbox',{name:'Your research question'}).fill(newQuestion);
  await page.getByRole('button',{name:'USE THIS QUESTION',exact:true}).click();
  assert.equal(await page.locator('.research-cockpit').getAttribute('data-measured'),'false');
  assert.equal(await page.locator('.scientist-next').count(),0);
  await overflow('synthetic-new-question');
  await nav('Evidence');
  assert.match(await page.locator('main').innerText(),/This question has not been tested yet/);
  const history = page.locator('details.panel').filter({has:page.locator('summary').filter({hasText:'HISTORICAL / RETAINED RECORDS'})});
  assert.equal(await history.count(),1);
  await history.locator('summary').first().click();
  assert.match(await history.innerText(),/Does silencing primary_a/);
  await history.locator('summary').first().click();
  await overflow('evidence-after-new-question');
  if (width===1920) await page.screenshot({path:`${dir}/synthetic-new-question-history.png`});
  await page.getByRole('button',{name:'Ask CausalFly',exact:true}).click();
  assert.equal(await assistant.locator('.assistant-response').count(),0);
  assert.equal(await assistant.locator('.assistant-meta').count(),0);
  await assistant.getByLabel('Ask about this experiment').fill('What changed under intervention?');
  await assistant.getByRole('button',{name:'Submit question locally'}).click();
  assert.match(await assistant.locator('.assistant-answer').innerText(),/This question has not been tested yet/);
  assert.doesNotMatch(await assistant.locator('.assistant-answer').innerText(),/Output peak:/);
  await page.getByRole('button',{name:'Close CausalFly Assistant'}).click();
  await nav('Live Connectome');
  const toggle = page.getByRole('button',{name:/^Sources & connection/});
  if (width===390 && await toggle.getAttribute('aria-expanded')==='false') await toggle.click();
  await sourceButton().click();
  await emit({source:'FRUITFLY_XR',state:'ERROR',message:'Offline fixture: observatory endpoint unavailable.',evidence:null});
  assert.match(await page.locator('.source-card').innerText(),/ERROR/);
  await page.getByRole('button',{name:'Stage 03: UNDERSTAND',exact:true}).click();
  assert.match(await page.locator('.xr-question-answer').innerText(),/No question submitted/);
  assert.match(await page.locator('.xr-local-analysis').innerText(),/No validated simulation frame/);
  await page.getByRole('button',{name:/^Stage 01: QUESTION/}).click();
  await sourceButton().click();
  for (const snapshot of xr.snapshots.slice(0,2)) await emit({...snapshot,retentionId:'offline-fixture'});
  assert.equal(await sourceButton().innerText(),'Disconnect');
  await page.getByRole('button',{name:'Set Investigation Question',exact:true}).click();
  const question = await page.locator('.retained-investigation').innerText();
  await page.getByRole('button',{name:'Stage 03: UNDERSTAND',exact:true}).click();
  assert.match(await page.locator('.xr-local-analysis').innerText(),/No validated simulation frame/);
  assert.equal(await page.getByRole('button',{name:'Explain with Meta',exact:false}).isEnabled(),false);
  await nav('Evidence');
  assert.match(await page.locator('main').innerText(),/No evidence observed for this question yet/);
  assert.match(await page.locator('main').innerText(),/HISTORICAL \/ RETAINED RECORDS/);
  await overflow('fruitfly-historical-after-question');
  await page.getByRole('button',{name:'Ask CausalFly',exact:true}).click();
  await assistant.getByRole('button',{name:'Ask about my investigation question'}).click();
  assert.match(await assistant.locator('.assistant-answer').innerText(),/not support|No retained|not enough|insufficient/i);
  await page.getByRole('button',{name:'Close CausalFly Assistant'}).click();
  // Explicit fixture with a receipt after question submission; never sent to a provider.
  const fresh = {...xr.snapshots[2],retentionId:'offline-fixture',evidence:{...xr.snapshots[2].evidence,receivedAt:new Date().toISOString()}};
  await emit(fresh);
  await nav('Live Connectome');
  await page.getByRole('button',{name:'Stage 03: UNDERSTAND',exact:true}).click();
  assert.doesNotMatch(await page.locator('.xr-local-analysis').innerText(),/No validated simulation frame/);
  assert.equal(await page.getByRole('button',{name:'Explain with Meta',exact:false}).isEnabled(),true);
  await sourceButton().click();
  assert.match(await page.locator('main').innerText(),/Last|DISCONNECTED|historical/i);
  assert.match(await page.locator('.xr-local-analysis').innerText(),/Last snapshot retained/);
  await overflow('fruitfly-disconnected');
  if (width===1920) await page.screenshot({path:`${dir}/fruitfly-disconnected-active-observation.png`});
  await sourceButton().click();
  await emit({...fresh,state:'CONNECTED'});
  await page.getByRole('button',{name:/^Stage 01: QUESTION/}).click();
  assert.equal(await page.locator('.retained-investigation').innerText(),question);
  assert.equal(await sourceButton().innerText(),'Disconnect');
  checks.push({width,state:'reconnect-question-identity-preserved'});
  await context.close();
 }
 assert.deepEqual(errors,[]);
 fs.writeFileSync(`${dir}/browser-results.json`,JSON.stringify({checks,actions,errors,liveProviderCalls:0},null,2));
 console.log(JSON.stringify({checks:checks.length,actions:actions.length,errors,liveProviderCalls:0}));
} finally {await browser.close();}
